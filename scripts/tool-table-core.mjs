// README's tool count and tool tables, built from the code (BND-04).
//
// **Why this exists.** README's count was checked by a test, but its tables were
// not, and they drifted: three contact tools had no row. This file holds one row
// per tool and renders README's whole tool block from them. The test in
// test/tool-table.test.ts forces the set of rows to equal the set of tools the
// real server lists, so a new tool with no row turns the suite red.
//
// **It runs in two places, so it imports nothing from Node.** The test imports
// it inside the Workers pool, and scripts/tool-table.mjs imports it under Node.
// It follows scripts/grants-core.mjs for the same reason, and
// scripts/tool-table-core.d.mts carries its types.
//
// **It prints nothing.** Every function returns a value. The CLI decides what
// to print.
//
// **How to change a README tool line.** Edit the row below, then run
// `node scripts/tool-table.mjs --write`. Do not edit README between the markers:
// the check refuses a block that differs from what this file renders.

/** The comment that opens the generated block in README. */
export const START_MARKER =
  "<!-- tools:start. Generated by scripts/tool-table.mjs. Edit the lines in " +
  "scripts/tool-table-core.mjs, then run: node scripts/tool-table.mjs --write -->";

/** The comment that closes it. */
export const END_MARKER = "<!-- tools:end -->";

/** Every kind of finding `checkReadme` can report. */
export const FINDING_KINDS = Object.freeze([
  "markers-missing",
  "block-differs",
  "missing-row",
  "unregistered-row",
  "duplicate-row",
]);

const COUNT_WORDS = [
  "zero", "one", "two", "three", "four", "five",
  "six", "seven", "eight", "nine", "ten", "eleven", "twelve",
];

function group(heading, intro, rows) {
  return Object.freeze({
    heading,
    intro,
    rows: Object.freeze(rows.map(([name, line]) => Object.freeze({ name, line }))),
  });
}

