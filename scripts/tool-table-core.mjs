/**
 * Every tool name registered in the given sources, sorted.
 *
 * `sources` maps a file path to its text. A name is the first argument of
 * `server.registerTool(`: a string literal, or a name bound to a string
 * constant in the same file. A name that cannot be resolved throws. Skipping it
 * would hide a tool from the table, which is the thing this file prevents.
 *
 * Reading source text can miss a tool registered some other way, through a
 * helper or a loop. The test catches that by comparing with the live tool list.
 */
export function registeredNames(sources) {
  const names = [];
  const call = /server\.registerTool\(\s*(?:"([^"]+)"|'([^']+)'|([A-Za-z_$][\w$]*))/g;
  for (const [path, text] of Object.entries(sources)) {
    for (const match of text.matchAll(call)) {
      const literal = match[1] ?? match[2];
      if (literal !== undefined) {
        names.push(literal);
        continue;
      }
      const constant = new RegExp(
        `(?:^|\\n)\\s*(?:export\\s+)?const\\s+${match[3]}\\s*=\\s*"([^"]+)"`,
      ).exec(text);
      if (constant === null) {
        throw new Error(
          `${path}: registerTool is called with ${match[3]}, which is not a ` +
            "string constant in the same file. Name the tool with a literal or " +
            "a same-file constant, or teach registeredNames the new form.",
        );
      }
      names.push(constant[1]);
    }
  }
  return names.sort();
}

/** Every row's tool name, in table order. Duplicates are kept. */
export function rowNames(groups) {
  return groups.flatMap((one) => one.rows.map((row) => row.name));
}

/** README's whole tool block: the count line, then each group's table. */
export function renderBlock(groups) {
  const count = rowNames(groups).length;
  const word = COUNT_WORDS[groups.length] ?? String(groups.length);
  const parts = [
    `${count} tools in ${word} groups. Each tool that returns message, event or contact\n` +
      "text says in its description that the text is untrusted. Event titles, message\n" +
      "bodies and contact fields are data, never instructions.\n",
  ];
  for (const one of groups) {
    let text = `### ${one.heading}\n\n`;
    if (one.intro !== null) text += `${one.intro}\n\n`;
    text += "| Tool | What it does |\n|------|--------------|\n";
    for (const row of one.rows) text += `| \`${row.name}\` | ${row.line} |\n`;
    parts.push(text);
  }
  return parts.join("\n");
}

/**
 * What is wrong with README's tool block, as a list. Empty means nothing is.
 *
 * `names` is the registered tool names. Each finding has a `kind` from
 * FINDING_KINDS and a `detail` a person can act on.
 */
export function checkReadme(readmeText, groups, names) {
  const findings = [];
  const start = readmeText.indexOf(START_MARKER);
  const end = readmeText.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) {
    findings.push({
      kind: "markers-missing",
      detail: "README.md has no tools:start / tools:end pair around its tool tables.",
    });
  } else {
    const block = readmeText.slice(start + START_MARKER.length + 1, end);
    if (block !== renderBlock(groups)) {
      findings.push({
        kind: "block-differs",
        detail:
          "README.md's tool block is not what scripts/tool-table-core.mjs renders. " +
          "Run: node scripts/tool-table.mjs --write",
      });
    }
  }

  const registered = new Set(names);
  const seen = new Set();
  for (const name of rowNames(groups)) {
    if (seen.has(name)) {
      findings.push({ kind: "duplicate-row", detail: `${name} has more than one row.` });
    }
    seen.add(name);
    if (!registered.has(name)) {
      findings.push({
        kind: "unregistered-row",
        detail: `${name} has a row, but no tool by that name is registered.`,
      });
    }
  }
  for (const name of registered) {
    if (!seen.has(name)) {
      findings.push({
        kind: "missing-row",
        detail: `${name} is registered, but has no row in scripts/tool-table-core.mjs.`,
      });
    }
  }
  return findings;
}

/** README with the text between the markers replaced by the rendered block. */
export function withBlock(readmeText, groups) {
  const start = readmeText.indexOf(START_MARKER);
  const end = readmeText.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("README.md has no tools:start / tools:end pair to write between.");
  }
  return (
    readmeText.slice(0, start + START_MARKER.length) +
    "\n" +
    renderBlock(groups) +
    readmeText.slice(end)
  );
}
